function [filename, errcode] =  getRun(keyword, savePath, runsPath, runKey, isSave)

runs = what(runsPath);  %returns a structure array with all matlab files in the directory path

if isSave
    savePath = strcat(savePath, '\', runKey, '_raw_files');
    if ~exist(savePath)
        mkdir(savePath)
    end
end

instances = 0;

for i = 1:length(runs.mat)
    keyStart = findstr(runs.mat{i},keyword);    %use {} because runs.mat for string - is a cell array
    if ~isempty(keyStart)                       %look for nonempty response
        filename = strcat(runsPath, '\', runs.mat{i});
        if isSave
            if ~strcmpi(savePath, runsPath) % check that read and write folders not the same else no need to copy
                copyfile(filename, strcat(savePath, '\', runKey, '_', keyword, '.mat'))  %copy MAT file
                genFilePrefix = runs.mat{i}(1:keyStart-2);%get general file prefix to be able to copy across results for later reanalysis 
                if exist(strcat(runsPath, '\', genFilePrefix, '.erd'), 'file') % true when copying from TruckSim runs folders 
                    copyfile(strcat(runsPath, '\', genFilePrefix, '.erd'), strcat(savePath, '\', runKey, '_', keyword, '.erd'))  %copy across ERD file
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_end.par'), strcat(savePath, '\', runKey, '_', keyword, '_end.par'))  %copy across PARSFILE
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_all.par'), strcat(savePath, '\', runKey, '_', keyword, '_all.par'))  %copy across All PARSFILE
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_log.txt'), strcat(savePath, '\', runKey, '_', keyword, '_log.txt'))  %copy across log file
                else % this is when copying from raw files folder generated by PostProcess
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_' , keyword, '.erd'), strcat(savePath, '\', runKey, '_', keyword, '.erd'))  %copy across ERD file
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_' , keyword, '_end.par'), strcat(savePath, '\', runKey, '_', keyword, '_end.par'))  %copy across PARSFILE
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_' , keyword, '_all.par'), strcat(savePath, '\', runKey, '_', keyword, '_all.par'))  %copy across ALL PARSFILE
                    copyfile(strcat(runsPath, '\', genFilePrefix, '_' , keyword, '_log.txt'), strcat(savePath, '\', runKey, '_', keyword, '_log.txt'))  %copy across log file

                end
            end
        end

            instances = instances + 1;
    end
end

if instances == 0
    error(['ERROR: no file found containing  ' keyword])
    errcode = 0;
elseif instances == 1 && isSave == 1
    disp(['copied file containing  ' keyword])
    errcode = 1;
elseif instances == 1 && isSave == 0
    disp(['loaded file containing  ' keyword])
    errcode = 1;
else
    error(['ERROR: multiple instances of file containing  ' keyword])
    errcode = 2;
end

end
%findstr - looks for substring
